import seaborn as sns

### For more Seaborn dataset examples, check this repo: https://github.com/mwaskom/seaborn-data


# Tips: Dataset containing information about tips received by waitstaff in a restaurant.
tips = sns.load_dataset("tips")

# Iris: Classic dataset in machine learning, containing measurements for different species of iris flowers.
iris = sns.load_dataset("iris")

# Titanic: Dataset containing information about the passengers on the Titanic, including whether they survived.
titanic = sns.load_dataset("titanic")

# Penguins: Dataset providing data on different species of penguins, including physical measurements.
penguins = sns.load_dataset("penguins")

# Diamonds: Dataset containing data about diamonds, including their cut, color, clarity, carat, and price.
diamonds = sns.load_dataset("diamonds")

# Planets: Dataset providing information about exoplanets, including their discovery method, mass, and distance from Earth.
planets = sns.load_dataset("planets")

# Car Crashes: Dataset containing data on car crashes in the US, including metrics related to speed and alcohol.
car_crashes = sns.load_dataset("car_crashes")

# FMRI: Dataset containing data from an fMRI experiment, including information about brain regions and stimulus.
fmri = sns.load_dataset("fmri")

# Flights: Dataset containing information about flights in 2013 from NYC, including the carrier, flight number, and delays.
flights = sns.load_dataset("flights")
